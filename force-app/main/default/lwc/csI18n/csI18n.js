let current = null;

export function normalizeLang(value) {
    return String(value || '')
        .toLowerCase()
        .startsWith('fr')
        ? 'fr'
        : 'en';
}

/** The saved choice, else the user's Salesforce language (French or English only). */
export function defaultLang() {
    try {
        const saved = window.localStorage.getItem(STORAGE_KEY);
        if (saved) return normalizeLang(saved);
    } catch {
        // No storage: fall back to the user's language
    }
    return normalizeLang(USER_LANG);
}

/** The saved choice (read each time, so every component on the page agrees), else the last one set, else the user's language. */
export function getLang() {
    try {
        const saved = window.localStorage.getItem(STORAGE_KEY);
        if (saved) return normalizeLang(saved);
    } catch {
        // No storage: use the in-memory choice
    }
    return current || normalizeLang(USER_LANG);
}

export function setLang(lang) {
    current = normalizeLang(lang);
    try {
        window.localStorage.setItem(STORAGE_KEY, current);
    } catch {
        // No storage: the choice lasts until the page reloads
    }
    return current;
}

/** Locale for dates and numbers. */
export function localeFor(lang) {
    return LOCALES[normalizeLang(lang || getLang())];
}

/** Every text for the language, for templates: {L.save}. */
export function labels(lang) {
    return DICT[normalizeLang(lang || getLang())];
}

export function tr(key, params, lang) {
    const l = normalizeLang(lang || getLang());
    const dict = DICT[l];
    let k = key;
    if (params && typeof params.n === 'number' && dict[`${key}_one`] !== undefined) {
        const one = l === 'fr' ? Math.abs(params.n) < 2 : params.n === 1;
        k = `${key}_${one ? 'one' : 'other'}`;
    }
    let text = dict[k];
    if (text === undefined) text = DICT.en[k];
    if (text === undefined) return key;
    if (params) text = text.replace(/\{(\w+)\}/g, (m, p) => (params[p] === undefined || params[p] === null ? '' : String(params[p])));
    return text;
}
